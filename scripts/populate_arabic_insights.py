def update_data():
    # 1. Update studyTopics89.json
    print("Loading", STUDY_PATH)
    with open(STUDY_PATH, "r", encoding="utf-8") as f:
        study_data = json.load(f)

    all_study_ar = {**MATH_AR, **ENGLISH_AR, **PHYSICS_AR, **CHEMISTRY_AR}
    updated_study_count = 0
    for key, ar_fields in all_study_ar.items():
        if key in study_data:
            entry = study_data[key]
            for field in ["title", "summary", "principle", "example", "actionItem"]:
                if field in ar_fields:
                    if field not in entry:
                        entry[field] = {}
                    entry[field]["ar"] = ar_fields[field]
            updated_study_count += 1

    print(f"Updated {updated_study_count} items in studyTopics89.json with Arabic translations.")
    with open(STUDY_PATH, "w", encoding="utf-8") as f:
        json.dump(study_data, f, ensure_ascii=False, indent=2)

