Object.keys(extendedLanguages).forEach(loc => {
  workspaceTranslations[loc] = {
    ...workspaceTranslations.en,
    ...extendedLanguages[loc]
  };
});

// Update all 36 JSON files
const files = fs.readdirSync(messagesDir).filter(f => f.endsWith('.json'));
let updatedCount = 0;

files.forEach(file => {
  const filePath = path.join(messagesDir, file);
  const locale = file.replace('.json', '');
  const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  const baseEn = workspaceTranslations.en;
  const target = workspaceTranslations[locale] || {};

  content.workspace = {
    ...baseEn,
    ...target
  };

  fs.writeFileSync(filePath, JSON.stringify(content, null, 2) + '\n', 'utf8');
  updatedCount++;
});

console.log(`Successfully updated workspace translations in ${updatedCount} message files.`);
