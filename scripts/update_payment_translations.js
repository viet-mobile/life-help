const messagesDir = path.join(__dirname, '..', 'messages');
const files = fs.readdirSync(messagesDir).filter(f => f.endsWith('.json'));

let updatedCount = 0;

for (const file of files) {
  const lang = path.basename(file, '.json');
  const filePath = path.join(messagesDir, file);
  try {
    const raw = fs.readFileSync(filePath, 'utf8');
    const json = JSON.parse(raw);

    const trans = paymentTranslations[lang] || paymentTranslations.en;

    // Ensure customer.paymentLink
    if (!json.customer) json.customer = {};
    json.customer.paymentLink = trans.paymentLink;

    // Ensure payment section
    json.payment = {
      title: trans.title,
      subtitle: trans.subtitle,
      bankTransferInstruction: trans.bankTransferInstruction,
      bankNameLabel: trans.bankNameLabel,
      bankName: trans.bankName,
      accountNumberLabel: trans.accountNumberLabel,
      accountNumber: trans.accountNumber,
      accountHolderLabel: trans.accountHolderLabel,
      accountHolder: trans.accountHolder,
      copyAccountBtn: trans.copyAccountBtn,
      copySuccessToast: trans.copySuccessToast,
      noticeTitle: trans.noticeTitle,
      notice1: trans.notice1,
      notice2: trans.notice2,
      notice3: trans.notice3,
      liveChatBtn: trans.liveChatBtn,
      homeBtn: trans.homeBtn,
    };

    fs.writeFileSync(filePath, JSON.stringify(json, null, 2) + '\n', 'utf8');
    updatedCount++;
    console.log(`Updated ${file}`);
  } catch (err) {
    console.error(`Error updating ${file}:`, err);
  }
}

console.log(`Successfully updated ${updatedCount} message files.`);

