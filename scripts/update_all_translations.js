let updatedCount = 0;

files.forEach(file => {
  const filePath = path.join(messagesDir, file);
  const locale = file.replace('.json', '');
  const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  const baseEnWorkspace = i18nData.en.workspace;
  const baseEnTech = i18nData.en.tech;

  const targetLang = i18nData[locale] || {};
  const targetWorkspace = targetLang.workspace || {};
  const targetTech = targetLang.tech || {};

  content.workspace = {
    ...(content.workspace || {}),
    ...baseEnWorkspace,
    ...targetWorkspace,
  };

  content.tech = {
    ...(content.tech || {}),
    ...baseEnTech,
    ...targetTech,
  };

  fs.writeFileSync(filePath, JSON.stringify(content, null, 2) + '\n', 'utf8');
  updatedCount++;
});

console.log(`Successfully updated workspace and tech translations across all ${updatedCount} languages.`);

