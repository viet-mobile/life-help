def inject_asian_mideast():
    print("Injecting native dictionaries for South Asian, Southeast Asian & Middle East locales...")
    for code, data in ASIAN_MIDEAST_DICTS.items():
        target_path = os.path.join(MESSAGES_DIR, f"{code}.json")
        if not os.path.exists(target_path):
            continue
        with open(target_path, "r", encoding="utf-8") as f:
            content = json.load(f)

        for sec, keys in data.items():
            if sec not in content:
                content[sec] = {}
            for k, v in keys.items():
                content[sec][k] = v

        with open(target_path, "w", encoding="utf-8") as f:
            json.dump(content, f, ensure_ascii=False, indent=2)
            f.write("\n")
    print("Asian & Middle East locales patched successfully!")

if __name__ == "__main__":
    inject_asian_mideast()

