const locales = [
  'vi', 'en', 'zh-Hans', 'zh-Hant', 'mn', 'ru', 'uz', 'ne', 'hi', 'km',
  'th', 'my', 'ko', 'ja', 'id', 'si', 'kk', 'bn', 'ta', 'fr', 'de',
  'tr', 'uk', 'tet', 'ar', 'it', 'arz', 'es', 'fa', 'nl', 'pl', 'am',
  'sv', 'he', 'da', 'no'
];

locales.forEach(loc => {
  const filePath = path.join(__dirname, '..', 'messages', `${loc}.json`);
  if (!fs.existsSync(filePath)) return;
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  if (!data.chat) data.chat = {};

  const specific = allLangWorkstation[loc];
  if (specific) {
    for (const [k, v] of Object.entries(specific)) {
      data.chat[k] = v;
    }
  }

  // Ensure every file has the new workstation keys
  const keysToEnsure = [
    'workstationTitle', 'chattingWith', 'sessionStart', 'securitySessionBadge',
    'daysRemaining', 'langsActive', 'inquiryDefault', 'chatStarted',
    'quickHelloText', 'quickTechText', 'quickHousingText'
  ];

  keysToEnsure.forEach(k => {
    if (!data.chat[k]) {
      data.chat[k] = (allLangWorkstation[loc] && allLangWorkstation[loc][k]) ||
                     (allLangWorkstation['en'] && allLangWorkstation['en'][k]) ||
                     "";
    }
  });

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
});

