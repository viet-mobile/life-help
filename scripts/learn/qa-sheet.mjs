#!/usr/bin/env node
// Generates the manual staging QA sheet of the topic lessons added from the curriculum mapping:
//   node scripts/learn/qa-sheet.mjs            write docs/learning/qa/new-lessons-staging-qa.md
//   node scripts/learn/qa-sheet.mjs --check    fail if the committed sheet is stale
// Reads the canonical (Korean) bundles only; nothing is sent anywhere.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const read = (rel) => JSON.parse(fs.readFileSync(path.join(root, rel), "utf8"));
const HOST = "https://life-help-staging.simpl2eye.workers.dev";
// tranche 1: first topic tranche; tranche 2: second tranche (the lessons of the QA request)
const TRANCHE = {
  1: ["math-e3-ari1", "math-e6-ari1", "math-e6-ari2", "math-m3-sta1", "math-h2-seq1", "math-h3-pro1"],
  2: ["math-h1-mat1", "math-h1-set1", "math-h1-fnc1", "math-h1-pol1", "math-h3-cal1", "math-h3-cnt1", "en-e3-abc1", "en-e3-snd1", "en-e6-seq1", "en-e6-pun1", "en-m2-sum1"],
};
const all = new Map();
const questions = new Map();
for (const site of ["math", "english"]) {
  for (const tier of ["elementary", "demo", "secondary"]) {
    const b = read(`lib/learn/content/${tier}/${site}.json`);
    for (const q of b.questions) questions.set(q.id, q);
    for (const c of b.catalog.courses) for (const u of c.units) for (const l of u.lessons) all.set(l.id, { ...l, site, grade: c.grade, courseId: c.id, elective: !!c.elective });
  }
}
const clip = (s, n) => { const t = s.replace(/\s+/g, " ").trim(); return t.length > n ? t.slice(0, n - 1) + "…" : t; };
const cell = (s) => String(s).replace(/\|/g, "\\|");
function correct(q) {
  const a = q.answer;
  if (a.kind === "numeric") return String(a.value);
  if (a.kind === "choice") return q.type === "true_false" ? (a.id === "true" ? "맞다" : "틀리다") : `${a.id}) ${q.options.find((o) => o.id === a.id)?.text}`;
  return JSON.stringify(a);
}
function wrong(q) {
  const a = q.answer;
  if (a.kind === "numeric") return String(Number((a.value + 1).toFixed(4)));
  if (q.type === "true_false") return a.id === "true" ? "틀리다" : "맞다";
  const o = q.options.find((x) => x.id !== a.id);
  return `${o.id}) ${o.text}`;
}
const lines = [];
const out = (s = "") => lines.push(s);
out(`# 신규 토픽 레슨 스테이징 수동 QA 시트

GENERATED by \`scripts/learn/qa-sheet.mjs\` from the committed content. 직접 편집하지 마세요. 대상 Worker: \`${HOST}\` (스테이징 전용).

## 범위 확인

- **2차 묶음 11개**(이 시트의 본문): 수학 6(H1 4, H3 2) + 영어 5(E3 2, E6 2, M2 1). 학년이 한 곳에 몰려 있지 않습니다.
- **1차 묶음 6개**(부록): 수학 E3 1, E6 2, M3 1, H2 1, H3 1. 이전 단계에서 추가되었고 사람 확인이 아직 없습니다.
- \`수열의 합과 ∑\`는 1차 묶음의 **H2** 레슨입니다.

## 접근 방법 (게스트, 계정 불필요)

1. 새 시크릿 창에서 \`${HOST}/study/math/onboarding\`(영어는 \`/study/english/onboarding\`)을 엽니다.
2. 별명을 넣고 **해당 레슨의 학년**을 고른 뒤 목표를 고르고 시작합니다. 학습자는 자기 학년의 코스만 보입니다. H2·H3 학습자에게는 선택과목 코스가 함께 보입니다.
3. 레슨 직접 주소 \`/study/<math|english>/lesson/<레슨 ID>\`로 들어갑니다. 열리지 않으면 \`/study/<site>/learn\`에서 코스 경로로 들어가세요. 다른 학년의 레슨은 보이지 않거나 열리지 않는 것이 정상입니다.
4. 학년을 바꿔 보려면 \`/study/<site>/profile\` 또는 시크릿 창을 새로 엽니다(게스트 프로필은 브라우저에 저장됩니다).
5. 이 확인은 스테이징 DB에 쓰지 않습니다(게스트 진도는 브라우저에만 저장).

## 모든 레슨에 공통인 점검 항목

| # | 점검 | 합격 기준 |
|---|---|---|
| C1 | 레슨 시작 화면 | 제목·개념 설명·예시가 보이고 깨진 기호(\`$\`, \`\\\\\`, \`**\`)가 없음 |
| C2 | 문제 풀이 | 아래 표의 문항이 순서대로 나오고, 유형(숫자 입력 / 선택 / 참거짓)이 표와 같음 |
| C3 | 오답 → 힌트 | 오답 입력 후 1차 안내(\`아직이에요, 힌트를 볼게요.\`)와 힌트 1이 나옴. 한 번 더 틀리면 더 구체적인 힌트 2 |
| C4 | 힌트 버튼 | \`힌트 보기\`로 힌트가 차례로 열리고 다 열면 \`더 이상 힌트가 없어요\` |
| C5 | 정답 처리 | 정답 입력 시 \`정답이에요!\`, 해설이 표의 정답과 일치 |
| C6 | 풀이 공개 | 계속 틀리면 풀이를 보여 주고 다음으로 넘어갈 수 있음 |
| C7 | 도전 문제 | 핵심 4문항 뒤에 도전 문제 1개가 나옴(표의 \`c\`) |
| C8 | 완료 | 결과 화면, 별/XP 표시, 코스 경로로 돌아가기 가능 |
| C9 | 다국어 | 아래 언어에서 안내문·힌트·해설이 해당 언어이고 수식(\`$…$\`)과 영어 예문·선택지가 깨지지 않음. **정답 키와 문항 구성은 언어를 바꿔도 같아야 함** |
| C10 | 반응형 | 폭 390px와 1280px에서 가로 넘침 없음 |
| C11 | 콘솔 | 브라우저 개발자 도구 콘솔에 빨간 오류 없음(\`ERR_*\` 외부 확장 제외) |

### 언어 점검 대상 (C9)

- **오른쪽→왼쪽(RTL)**: \`ar\`, \`arz\`, \`fa\`, \`he\`, \`ur\` — 문장 방향은 RTL, 수식·영어 예문은 LTR로 섞여도 읽을 수 있어야 하고 화면이 밀리지 않아야 합니다.
- **저자원 감수 대상**: \`sg\`, \`tet\`, \`am\`, \`km\`, \`my\`, \`kk\`, \`kn\`, \`ml\` — 문장이 어색하거나 용어가 틀린 곳을 아래 \`메모\`에 적어 주세요(감수 자료로 쓰입니다).
- **대표**: \`en\`, \`vi\`, \`ja\`, \`zh-Hans\`, \`hi\`, \`sw\`.
- 언어는 화면 상단 언어 선택에서 바꿉니다.

판정 표기: ✅ 통과 / ❌ 실패(메모) / ➖ 해당 없음.
`);
function sheet(ids, title) {
  out(`\n## ${title}\n`);
  out("| 레슨 | 학년 | 사이트 | 직접 주소 |\n|---|---|---|---|");
  for (const id of ids) { const l = all.get(id); out(`| ${l.title} (\`${id}\`) | ${l.grade}${l.elective ? " 선택" : ""} | ${l.site} | ${HOST}/study/${l.site}/lesson/${id} |`); }
  for (const id of ids) {
    const l = all.get(id);
    out(`\n### ${l.title} — \`${id}\` (${l.grade}, ${l.site})\n`);
    out(`- 코스: \`${l.courseId}\`${l.elective ? " (선택과목 코스: H2·H3 학습자에게 보임)" : ""} · 학습 경로: ${HOST}/study/${l.site}/learn`);
    out(`- 개념(시작 화면): ${clip(l.concept, 140)}`);
    out(`- 예시: ${clip(String(l.example ?? ""), 100)}\n`);
    out("| 문항 | 유형·난도 | 문제(앞부분) | 정답 | 일부러 입력할 오답 | 힌트 수 | 결과 |\n|---|---|---|---|---|---:|---|");
    const ids2 = [...l.questionIds, ...(l.challengeId ? [l.challengeId] : [])];
    for (const qid of ids2) {
      const q = questions.get(qid);
      out(`| \`${qid}\` | ${q.type} d${q.difficulty}${qid === l.challengeId ? " (도전)" : ""} | ${cell(clip(q.prompt, 90))} | ${cell(correct(q))} | ${cell(wrong(q))} |  ${q.hints.length} |  |`);
    }
    out(`\n변형 문항(재도전·복습에서 나올 수 있음): ${[...questions.values()].filter((q) => q.skillId === l.skillIds[0] && q.role === "variant").map((q) => `\`${q.id}\``).join(", ") || "없음"}`);
    out("\n공통 점검: C1 ☐ C2 ☐ C3 ☐ C4 ☐ C5 ☐ C6 ☐ C7 ☐ C8 ☐ C9(RTL) ☐ C9(저자원) ☐ C10 ☐ C11 ☐ · 메모:\n");
  }
}
for (const id of [...TRANCHE[1], ...TRANCHE[2]]) if (!all.has(id)) throw new Error(`lesson missing: ${id}`);
sheet(TRANCHE[2], "본문 — 2차 묶음 11개");
sheet(TRANCHE[1], "부록 — 1차 묶음 6개");
out("\n## 레슨별 특이 점검\n");
out("- **행렬(`math-h1-mat1`)**: 문제의 행렬 두 개가 괄호로 정확히 그려지는지(KaTeX), 좁은 화면에서 가로 스크롤로 잘리지 않는지.");
out("- **집합(`math-h1-set1`)**: 중괄호 `{ }`가 깨지지 않는지, 참거짓 문항의 `맞다/틀리다` 버튼이 보이는지.");
out("- **미분(`math-h3-cal1`)**: `e^{2x}`, `\\frac`, `\\ln` 렌더링, 분수 분수 정답은 `0.25`와 `1/4` 둘 다 정답으로 처리되어야 하고(채점 코드가 분수·소수 입력을 모두 받음) `0.3`은 오답이어야 함. 소수 허용 오차 `0.001` 문항이므로 `0.2501`은 정답 처리될 수 있음.");
out("- **영어 5개**: 지시문만 학습자 언어이고 영어 단어·문장·선택지는 항상 영어여야 합니다. 영어 `en-e6-seq1`·`en-m2-sum1`은 본문을 따옴표로 묶어 듣기 기능(영어/한국어 번갈아 듣기) 대상이 되므로 듣기 기능이 문항에서 열리는지, 문장별 재생과 한국어 뜻이 나오는지 확인합니다(기능 위치는 레슨 화면에서 직접 찾아 메모해 주세요).");
out("- **선택지 순서**: 같은 문항을 다시 열 때 선택지 순서가 바뀌어도 정답 처리가 맞는지(정답은 위치가 아니라 선택지 ID로 판정).");
const text = lines.join("\n") + "\n";
const file = path.join(root, "docs/learning/qa/new-lessons-staging-qa.md");
if (process.argv.includes("--check")) { if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) { console.error("QA sheet is stale: run node scripts/learn/qa-sheet.mjs"); process.exit(1); } console.log("QA sheet up to date"); }
else { fs.writeFileSync(file, text); console.log(`wrote ${path.relative(root, file)}: ${TRANCHE[1].length + TRANCHE[2].length} lessons`); }
