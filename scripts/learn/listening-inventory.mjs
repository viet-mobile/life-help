// Mechanical inventory of every listenable English segment (lesson examples + reading passages) and its canonical Korean.
//   node --no-warnings scripts/learn/listening-inventory.mjs          writes docs/learning/english-bilingual-listening-inventory.md
//   node --no-warnings scripts/learn/listening-inventory.mjs --check  fails when the committed file is stale or coverage is not 100 %
// Reads the canonical content only; derives segments with the same functions the app uses.
import fs from "node:fs";
import { exampleItems, passageText, splitSentences } from "../../lib/learn/listen/segments.ts";
import { EXAMPLE_EXCLUDED, EXAMPLE_KO } from "../../lib/learn/content/listening/examples-ko.ts";
import { PASSAGE_KO } from "../../lib/learn/content/listening/passages-ko.ts";

const OUT = "docs/learning/english-bilingual-listening-inventory.md";
const SOURCES = { demo: "lib/learn/content/demo/english.json", elementary: "lib/learn/content/elementary/english.json", secondary: "lib/learn/content/secondary/english.json" };
const HANGUL = /[가-힯]/;
const esc = (s) => String(s).replace(/\|/g, "\\|");

export function inventory() {
  const rows = [], excluded = [];
  const passageRows = new Map();
  for (const [, file] of Object.entries(SOURCES)) {
    const bundle = JSON.parse(fs.readFileSync(file, "utf8"));
    const gradeOfSkill = new Map();
    for (const c of bundle.catalog.courses) {
      for (const u of c.units) for (const l of u.lessons) {
        for (const s of l.skillIds) gradeOfSkill.set(s, c.grade);
        const items = exampleItems(l.example);
        if (!items.length) { excluded.push({ grade: c.grade, lesson: l.id, example: l.example, reason: EXAMPLE_EXCLUDED[l.id] ?? "(no reason recorded)", file }); continue; }
        const ko = EXAMPLE_KO[l.id] ?? [];
        items.forEach((it, i) => rows.push({ kind: "example", grade: c.grade, lesson: l.id, id: `ex-${l.id}:${i}`, en: it.en, ko: ko[i] ?? null, file }));
      }
    }
    for (const q of bundle.questions) {
      const passage = passageText(q.prompt);
      if (!passage) continue;
      const e = passageRows.get(passage) ?? { grade: gradeOfSkill.get(q.skillId) ?? "?", questions: [], file };
      e.questions.push(q.id);
      passageRows.set(passage, e);
    }
  }
  let p = 0;
  for (const [passage, e] of passageRows) {
    p++;
    const ko = PASSAGE_KO[passage] ?? [];
    splitSentences(passage).forEach((en, i) => rows.push({ kind: "passage", grade: e.grade, lesson: `P${String(p).padStart(2, "0")} (${e.questions.length} q: ${e.questions.slice(0, 3).join(", ")}${e.questions.length > 3 ? ", ..." : ""})`, id: `passage-${p}:${i}`, en, ko: ko[i] ?? null, file: e.file }));
  }
  const total = rows.length, withKo = rows.filter((r) => r.ko && HANGUL.test(r.ko)).length;
  return { rows, excluded, total, withKo, missing: total - withKo, passages: passageRows.size, questionsWithPassage: [...passageRows.values()].reduce((a, e) => a + e.questions.length, 0) };
}

export function render(inv) {
  const L = [];
  L.push("# English bilingual listening: inventory (generated)\n");
  L.push("Generated by `node --no-warnings scripts/learn/listening-inventory.mjs` from the canonical content (`lib/learn/content/{demo,elementary,secondary}/english.json`) and the authored Korean (`lib/learn/content/listening/{examples-ko,passages-ko}.ts`). Segments are derived with the same functions the app uses (`lib/learn/listen/segments.ts`). Do not edit by hand; `--check` fails when it is stale.\n");
  L.push(`* TOTAL_ENGLISH_SEGMENTS = ${inv.total} (lesson examples ${inv.rows.filter((r) => r.kind === "example").length}, reading-passage sentences ${inv.rows.filter((r) => r.kind === "passage").length} in ${inv.passages} distinct passages used by ${inv.questionsWithPassage} questions)`);
  L.push(`* WITH_CANONICAL_KOREAN = ${inv.withKo}`);
  L.push(`* MISSING_CANONICAL_KOREAN = ${inv.missing}`);
  L.push(`* EXCLUDED_LESSONS (no English to speak) = ${inv.excluded.length}\n`);
  L.push("## Excluded on purpose\n\n| grade | lesson | example | reason | source |\n|---|---|---|---|---|");
  for (const e of inv.excluded) L.push(`| ${e.grade} | ${e.lesson} | ${esc(e.example)} | ${esc(e.reason)} | ${e.file} |`);
  L.push("\n## Every listenable segment\n\n| grade | lesson / passage | segment id | English | Korean | source |\n|---|---|---|---|---|---|");
  for (const r of inv.rows) L.push(`| ${r.grade} | ${esc(r.lesson)} | ${r.id} | ${esc(r.en)} | ${r.ko ? esc(r.ko) : "**MISSING**"} | ${r.file} |`);
  L.push("");
  return L.join("\n");
}

if (process.argv[1]?.endsWith("listening-inventory.mjs")) {
  const inv = inventory();
  const text = render(inv);
  if (process.argv.includes("--check")) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
    if (cur !== text) { console.error(`${OUT} is stale: run node --no-warnings scripts/learn/listening-inventory.mjs`); process.exit(1); }
    if (inv.missing !== 0) { console.error(`MISSING_CANONICAL_KOREAN = ${inv.missing}`); process.exit(1); }
    console.log(`OK: ${inv.total} segments, ${inv.withKo} with canonical Korean, missing ${inv.missing}`);
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${OUT}: total ${inv.total}, with Korean ${inv.withKo}, missing ${inv.missing}, excluded lessons ${inv.excluded.length}`);
  }
}
