// Generates lib/learn/content/overlayIndex.ts: the static map of every presentation overlay file present under
// lib/learn/content/i18n/<locale>/<site>.json (plus the generated Vietnamese overlays in lib/learn/content/vi/).
// Static import() calls keep the bundler able to see every file; nothing is loaded until a locale is requested.
//
//   node scripts/learn/build-overlay-index.mjs          write the index
//   node scripts/learn/build-overlay-index.mjs --check  fail if the committed index is stale
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const dir = path.join(root, "lib/learn/content/i18n");
const SITES = ["math", "english", "korean"];
const entries = [];
for (const loc of fs.existsSync(dir) ? fs.readdirSync(dir).sort() : []) {
  for (const site of SITES) {
    if (fs.existsSync(path.join(dir, loc, `${site}.json`))) entries.push([loc, site, [`./i18n/${loc}/${site}.json`]]);
  }
}
// Vietnamese: generated by build-elementary-content / build-secondary-content (elementary + demo, secondary).
entries.push(["vi", "math", ["./vi/math.json", "./vi/secondary-math.json"]], ["vi", "english", ["./vi/english.json", "./vi/secondary-english.json"]]);

const byLocale = new Map();
for (const [loc, site, files] of entries) {
  if (!byLocale.has(loc)) byLocale.set(loc, []);
  byLocale.get(loc).push([site, files]);
}
const q = (s) => (/^[a-z]+$/.test(s) ? s : JSON.stringify(s));
const lines = [...byLocale.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([loc, sites]) =>
  `  ${q(loc)}: {\n${sites.map(([site, files]) => `    ${site}: () => Promise.all([${files.map((f) => `import("${f}")`).join(", ")}]).then((m) => mergeOverlays(...m.map((x) => x.default as ContentOverlay))),`).join("\n")}\n  },`);
const text = `// GENERATED by scripts/learn/build-overlay-index.mjs - do not edit by hand.
import type { LearnLocale } from "@/lib/learn/i18n";
import type { Site } from "@/lib/learn/types";
import { mergeOverlays, type ContentOverlay } from "./overlay";

export const OVERLAY_LOADERS: Partial<Record<LearnLocale, Partial<Record<Site, () => Promise<ContentOverlay>>>>> = {
${lines.join("\n")}
};
`;
const file = path.join(root, "lib/learn/content/overlayIndex.ts");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) { console.error("overlay index is stale: run node scripts/learn/build-overlay-index.mjs"); process.exit(1); }
  console.log(`overlay index ok (${entries.length} overlays)`);
} else {
  fs.writeFileSync(file, text);
  console.log(`wrote overlay index (${entries.length} overlays)`);
}
