#!/usr/bin/env node
// Generates docs/learning/curriculum-2022-coverage.md from the official 2022 standards JSON and the reviewed mappings
// (docs/learning/curriculum-mappings/reviewed.json). Usage: node scripts/learn/curriculum-coverage-doc.mjs <content-revision>
import fs from "node:fs";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { buildAudit, readContent, contentSourceFiles } from "../curriculum/audit-moe-2022.mjs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const mappingPath = path.join(root, "docs/learning/curriculum-mappings/reviewed.json");
const outputPath = path.join(root, "docs/learning/curriculum-2022-coverage.md");
const SUBJECTS = [
  ["mathematics", "수학"],
  ["english", "영어"],
];
const contentFiles = (subject) => contentSourceFiles(root, subject);
const digest = (value) => createHash("sha256").update(value).digest("hex");

export function renderCoverageDoc(
  rev,
  mappings = JSON.parse(fs.readFileSync(mappingPath, "utf8")),
) {
  if (!/^[a-f0-9]{7,40}$/.test(rev))
    throw new Error("Supply the actual content commit (7-40 hex digits)");
  const audits = new Map(
    SUBJECTS.map(([subject]) => {
      if (!Array.isArray(mappings[subject])) throw new Error(`Missing ${subject} mapping array`);
      const data = JSON.parse(
        fs.readFileSync(path.join(root, `lib/learn/curriculum/kr/2022/${subject}.json`), "utf8"),
      );
      return [subject, buildAudit(data, readContent(root, subject), mappings[subject])];
    }),
  );
  const STATUS = ["covered", "partial", "gap", "unreviewed"];
  const out = [];
  out.push(`# 2022 개정 교육과정 성취기준과 현재 학습 콘텐츠의 대응표

GENERATED by \`scripts/learn/curriculum-coverage-doc.mjs\` from \`lib/learn/curriculum/kr/2022/{mathematics,english}.json\` (교육부 고시 제2022-33호, 커밋 8b5d815) and \`docs/learning/curriculum-mappings/reviewed.json\`. 직접 편집하지 마세요.

- 검토한 콘텐츠 커밋: \`${rev}\`.
- 판정은 Claude의 자동 검토이며 신규 콘텐츠 관련 근거는 ChatGPT가 추가 확인했습니다. 전체 705개 기준의 교육적 충족 여부를 독립 재판정한 것은 아닙니다. **교사·원어민 검토를 받지 않았습니다**. \`covered\`도 검토자의 판정이지 교육적 완전성의 증명이 아닙니다. \`unreviewed\`는 누락이 아닙니다.
- 객관식·단답 문항은 계산·식별 기능만 입증하는 것으로 보았습니다. 서술·말하기·쓰기·탐구·공학도구 활동이 필요한 기준은 해당 문항이 없으면 \`covered\`로 판정하지 않았습니다.
- 영어 E1·E2 레슨은 공식 교육과정(초 3~4학년군부터)과 무관한 확장 콘텐츠이며 근거로 쓰지 않았습니다.
- 학기 배치(\`lib/learn/content/semesters.ts\`)는 이 사이트의 편성 판단이며 교육부가 지정한 학기가 아닙니다.
`);
  out.push(`- 매핑 SHA-256: \`${digest(JSON.stringify(mappings))}\`.
`);
  out.push("| 콘텐츠 스냅샷 | 레슨 | 문항 | 콘텐츠 SHA-256 |\n|---|---:|---:|---|");
  for (const [subject, label] of SUBJECTS) {
    const audit = audits.get(subject);
    const fingerprint = digest(
      JSON.stringify(
        contentFiles(subject).map((file) => [file, digest(fs.readFileSync(path.join(root, file)))]),
      ),
    );
    out.push(
      `| ${label} | ${audit.summary.lessons} | ${audit.summary.questions} | \`${fingerprint}\` |`,
    );
  }
  out.push("\n전체 문항 수는 일반 문항과 은행의 연습 문항을 합친 수입니다. 은행은 기존 skill에 연결된 variant이며 새 레슨이나 배치 진단 문항으로 집계하지 않습니다. 은행 문항 수만으로 성취기준 상태를 상향하지 않습니다.\n");
  out.push(
    "\n문서 생성 시 모든 매핑의 코드·ID·공개 상태·레슨 연결을 검증했습니다. 구조 검증은 교사 검토를 대신하지 않습니다.\n",
  );
  for (const [subject, label] of SUBJECTS) {
    const data = JSON.parse(
      fs.readFileSync(path.join(root, `lib/learn/curriculum/kr/2022/${subject}.json`), "utf8"),
    );
    const courses = new Map(data.courses.map((c) => [c.id, c.title ?? c.name]));
    const m = new Map(mappings[subject].map((e) => [e.code, e]));
    const groups = new Map();
    for (const s of data.achievement_standards) {
      const key =
        s.grade_band === "고등학교" ? `고등학교 — ${courses.get(s.course_id)}` : s.grade_band;
      if (!groups.has(key)) groups.set(key, []);
      groups.get(key).push(s);
    }
    const tot = Object.fromEntries(STATUS.map((k) => [k, 0]));
    out.push(
      `## ${label}\n\n| 학년군 / 과목 | 성취기준 | covered | partial | gap | unreviewed |\n|---|---:|---:|---:|---:|---:|`,
    );
    const body = [];
    for (const [key, list] of groups) {
      const c = Object.fromEntries(STATUS.map((k) => [k, 0]));
      for (const s of list) c[m.get(s.code)?.status ?? "unreviewed"]++;
      STATUS.forEach((k) => (tot[k] += c[k]));
      out.push(
        `| ${key} | ${list.length} | ${c.covered} | ${c.partial} | ${c.gap} | ${c.unreviewed} |`,
      );
      body.push(`### ${label} — ${key}\n`);
      for (const st of ["gap", "partial"]) {
        const rows = list.filter((s) => (m.get(s.code)?.status ?? "unreviewed") === st);
        if (!rows.length) continue;
        body.push(`**${st}** (${rows.length}): ${rows.map((s) => `\`${s.code}\``).join(" ")}\n`);
      }
    }
    out.push(
      `| **합계** | ${data.achievement_standards.length} | ${tot.covered} | ${tot.partial} | ${tot.gap} | ${tot.unreviewed} |\n`,
    );
    out.push(...body);
  }
  out.push(
    "기준별 근거(레슨·문항 ID, 판단 이유)는 `docs/learning/curriculum-mappings/reviewed.json`에 있습니다. 검증: `node scripts/curriculum/audit-moe-2022.mjs --mappings docs/learning/curriculum-mappings/reviewed.json --content-revision <커밋> --curriculum-revision 8b5d815`.\n",
  );
  return out.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rev = process.argv.slice(2).find((arg) => !arg.startsWith("--"));
  const body = renderCoverageDoc(rev);
  // A caller may not label new working-tree content as an older commit.
  for (const [subject] of SUBJECTS)
    for (const file of contentFiles(subject)) {
      const committed = execFileSync("git", ["show", `${rev}:${file}`], {
        cwd: root,
        maxBuffer: 20 * 1024 * 1024,
      });
      if (!committed.equals(fs.readFileSync(path.join(root, file))))
        throw new Error(`Content does not match ${rev}: ${file}`);
    }
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(outputPath, "utf8") !== body)
      throw new Error("Coverage document is stale; regenerate for the current content commit");
    console.log("coverage document is validated and up to date");
  } else {
    fs.writeFileSync(outputPath, body);
    console.log("wrote validated docs/learning/curriculum-2022-coverage.md");
  }
}
