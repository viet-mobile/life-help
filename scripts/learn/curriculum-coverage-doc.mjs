#!/usr/bin/env node
// Generates docs/learning/curriculum-2022-coverage.md from the official 2022 standards JSON and the reviewed mappings
// (docs/learning/curriculum-mappings/reviewed.json). Usage: node scripts/learn/curriculum-coverage-doc.mjs <content-revision>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const rev = process.argv[2] ?? "UNKNOWN";
const mappings = JSON.parse(fs.readFileSync(path.join(root, "docs/learning/curriculum-mappings/reviewed.json"), "utf8"));
const STATUS = ["covered", "partial", "gap", "unreviewed"];
const out = [];
out.push(`# 2022 개정 교육과정 성취기준과 현재 학습 콘텐츠의 대응표

GENERATED by \`scripts/learn/curriculum-coverage-doc.mjs\` from \`lib/learn/curriculum/kr/2022/{mathematics,english}.json\` (교육부 고시 제2022-33호, 커밋 8b5d815) and \`docs/learning/curriculum-mappings/reviewed.json\`. 직접 편집하지 마세요.

- 검토한 콘텐츠 커밋: \`${rev}\`.
- 판정은 Claude의 자동 검토이며 **교사·원어민 검토를 받지 않았습니다**. \`covered\`도 검토자의 판정이지 교육적 완전성의 증명이 아닙니다. \`unreviewed\`는 누락이 아닙니다.
- 객관식·단답 문항은 계산·식별 기능만 입증하는 것으로 보았습니다. 서술·말하기·쓰기·탐구·공학도구 활동이 필요한 기준은 해당 문항이 없으면 \`covered\`로 판정하지 않았습니다.
- 영어 E1·E2 레슨은 공식 교육과정(초 3~4학년군부터)과 무관한 확장 콘텐츠이며 근거로 쓰지 않았습니다.
- 학기 배치(\`lib/learn/content/semesters.ts\`)는 이 사이트의 편성 판단이며 교육부가 지정한 학기가 아닙니다.
`);
for (const [subject, label] of [["mathematics", "수학"], ["english", "영어"]]) {
  const data = JSON.parse(fs.readFileSync(path.join(root, `lib/learn/curriculum/kr/2022/${subject}.json`), "utf8"));
  const courses = new Map(data.courses.map((c) => [c.id, c.title ?? c.name]));
  const m = new Map(mappings[subject].map((e) => [e.code, e]));
  const groups = new Map();
  for (const s of data.achievement_standards) {
    const key = s.grade_band === "고등학교" ? `고등학교 — ${courses.get(s.course_id)}` : s.grade_band;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(s);
  }
  const tot = Object.fromEntries(STATUS.map((k) => [k, 0]));
  out.push(`## ${label}\n\n| 학년군 / 과목 | 성취기준 | covered | partial | gap | unreviewed |\n|---|---:|---:|---:|---:|---:|`);
  const body = [];
  for (const [key, list] of groups) {
    const c = Object.fromEntries(STATUS.map((k) => [k, 0]));
    for (const s of list) c[m.get(s.code)?.status ?? "unreviewed"]++;
    STATUS.forEach((k) => (tot[k] += c[k]));
    out.push(`| ${key} | ${list.length} | ${c.covered} | ${c.partial} | ${c.gap} | ${c.unreviewed} |`);
    body.push(`### ${label} — ${key}\n`);
    for (const st of ["gap", "partial"]) {
      const rows = list.filter((s) => (m.get(s.code)?.status ?? "unreviewed") === st);
      if (!rows.length) continue;
      body.push(`**${st}** (${rows.length}): ${rows.map((s) => `\`${s.code}\``).join(" ")}\n`);
    }
  }
  out.push(`| **합계** | ${data.achievement_standards.length} | ${tot.covered} | ${tot.partial} | ${tot.gap} | ${tot.unreviewed} |\n`);
  out.push(...body);
}
out.push("기준별 근거(레슨·문항 ID, 판단 이유)는 `docs/learning/curriculum-mappings/reviewed.json`에 있습니다. 검증: `node scripts/curriculum/audit-moe-2022.mjs --mappings docs/learning/curriculum-mappings/reviewed.json --content-revision <커밋> --curriculum-revision 8b5d815`.\n");
fs.writeFileSync(path.join(root, "docs/learning/curriculum-2022-coverage.md"), out.join("\n"));
console.log("wrote docs/learning/curriculum-2022-coverage.md");
