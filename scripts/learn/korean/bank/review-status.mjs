#!/usr/bin/env node
// Per-language completeness of the Korean review material -> lib/learn/review/korean-locale-status.json (shown on the review console).
//   node scripts/learn/korean/bank/review-status.mjs [--check]
// Course: the overlay must exist (build-content-assets refuses an overlay that leaves a learner-facing string untranslated).
// Bank: the 11 form templates and the g: / s: / n: texts of the bank. A language without a text shows the English one (flagged "fallback").
// All translations are AI translations; no language has had a native-speaker review.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../../..");
const bank = JSON.parse(fs.readFileSync(path.join(root, "lib/learn/content/bank/korean.json"), "utf8"));
const kitEn = JSON.parse(fs.readFileSync(path.join(root, "lib/learn/content/bank/korean-kit.en.json"), "utf8"));
const required = { g: new Set(), s: new Set(), n: new Set() };
for (const [sid, sk] of Object.entries(bank.skills)) {
  for (const it of sk.items) { if (it.c !== "syl") required.g.add(`g:${it.id}`); if (it.s) required.s.add(`s:${it.id}`); if (it.n) required.n.add(`n:${sid}:${it.n}`); }
}
const dir = path.join(root, "content/learn-overlays");
const locales = ["en", ...fs.readdirSync(dir).filter((l) => fs.existsSync(path.join(dir, l, "korean.json"))).sort()];
const out = { note: "AI translations, not native-speaker reviewed. generated by scripts/learn/korean/bank/review-status.mjs", required: { g: required.g.size, s: required.s.size, n: required.n.size, templates: Object.keys(kitEn.templates).length }, locales: {} };
for (const l of locales) {
  if (l === "en") { out.locales.en = { tier: "canonical", course: "canonical", templates: out.required.templates, g: out.required.g, s: out.required.s, n: out.required.n, missing: 0 }; continue; }
  const ov = JSON.parse(fs.readFileSync(path.join(dir, l, "korean.json"), "utf8"));
  const texts = ov.bank?.texts ?? {};
  const have = (set) => [...set].filter((k) => typeof texts[k] === "string" && texts[k].trim()).length;
  const rec = { course: "localized", templates: Object.keys(ov.bank?.templates ?? {}).length, g: have(required.g), s: have(required.s), n: have(required.n) };
  rec.missing = (out.required.g - rec.g) + (out.required.s - rec.s) + (out.required.n - rec.n) + (out.required.templates - rec.templates);
  rec.tier = rec.missing === 0 ? "complete" : "partial";
  out.locales[l] = rec;
}
const text = JSON.stringify(out, null, 1) + "\n";
const file = path.join(root, "lib/learn/review/korean-locale-status.json");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) { console.error("korean-locale-status.json is stale: run node scripts/learn/korean/bank/review-status.mjs"); process.exit(1); }
  console.log("korean-locale-status.json is up to date");
} else {
  fs.writeFileSync(file, text);
  const c = Object.values(out.locales).reduce((a, r) => (a[r.tier] = (a[r.tier] ?? 0) + 1, a), {});
  console.log("locale status:", c);
}
