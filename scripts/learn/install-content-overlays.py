#!/usr/bin/env python3
"""Install translated content-overlay chunks into lib/learn/content/i18n/<locale>/<site>.json.

  python3 scripts/learn/install-content-overlays.py <chunk-dir> [locale ...]

<chunk-dir>/out/<locale>/<site>-struct.json and <site>-qNN.json are the translator outputs (overlay shape) for the job files in
<chunk-dir>/jobs/. A locale is installed only when every chunk it has passes <chunk-dir>/check.py; a locale with all question chunks
of a site is FULL for that site, one with only the struct chunk is STRUCT (course / unit / lesson / skill texts; question texts fall back
to English at runtime). Writes lib/learn/content/i18n/coverage.json (the audit reads it).
"""
import json, os, subprocess, sys, glob

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
chunk_dir = os.path.abspath(sys.argv[1])
jobs = sorted(os.path.basename(p)[:-5] for p in glob.glob(f"{chunk_dir}/jobs/*.json"))
locales = sys.argv[2:] or sorted(os.listdir(f"{chunk_dir}/out"))
cov_path = os.path.join(ROOT, "lib/learn/content/i18n/coverage.json")
coverage = json.load(open(cov_path)) if os.path.exists(cov_path) else {}
# Corrections made to the canonical curriculum after the translations were produced (the translators copied the old text):
#   m-h3-ser-v3 float artifact; the unpaired $ in the m-h3-area-3 / -v3 explanations; e-e3-up-5b named the option by position.
FIXES_PATH = os.path.join(os.path.dirname(__file__), "overlay-fixes.json")
FIXES = json.load(open(FIXES_PATH, encoding="utf-8")) if os.path.exists(FIXES_PATH) else {}


def post_fix(loc, site, ov):
    for qid, q in ov.get("questions", {}).items():
        for f in ("prompt", "explanation"):
            if isinstance(q.get(f), str):
                q[f] = q[f].replace("44.99999999999999", "45")
                for a in ("2+2=4", "4.5+4.5=9"):
                    if a + "$" in q[f] and "$" + a + "$" not in q[f]:
                        q[f] = q[f].replace(a + "$", "$" + a + "$")
        q["hints"] = [h.replace("44.99999999999999", "45") for h in q.get("hints", [])] or q.get("hints")
        if q.get("hints") is None:
            q.pop("hints")
        fix = FIXES.get(site, {}).get(qid, {}).get(loc)
        if fix:
            q.update(fix)
for loc in locales:
    if loc in ("ko", "vi"):
        continue  # ko is canonical; vi is generated by build-elementary/secondary-content
    present = [j for j in jobs if os.path.exists(f"{chunk_dir}/out/{loc}/{j}.json")]
    if not present:
        continue
    r = subprocess.run([sys.executable, "check.py", loc, *present], cwd=chunk_dir, capture_output=True, text=True)
    if r.returncode != 0:
        print(f"{loc}: SKIPPED (check failed)\n{r.stdout[-800:]}")
        continue
    for site in ("math", "english"):
        site_jobs = [j for j in present if j.startswith(site + "-")]
        if not site_jobs:
            continue
        ov = {"skills": {}, "courses": {}, "units": {}, "lessons": {}, "questions": {}}
        for j in site_jobs:
            for k, v in json.load(open(f"{chunk_dir}/out/{loc}/{j}.json", encoding="utf-8")).items():
                ov[k].update(v)
        all_q = [j for j in jobs if j.startswith(site + "-q")]
        full = f"{site}-struct" in site_jobs and all(j in site_jobs for j in all_q)
        kind = "FULL" if full else ("STRUCT" if site_jobs == [f"{site}-struct"] else "PARTIAL")
        out = os.path.join(ROOT, f"lib/learn/content/i18n/{loc}/{site}.json")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        post_fix(loc, site, ov)
        ov = {k: dict(sorted(v.items())) for k, v in ov.items() if v}
        with open(out, "w", encoding="utf-8") as f:
            json.dump(ov, f, ensure_ascii=False, separators=(",", ":"))
            f.write("\n")
        coverage.setdefault(loc, {})[site] = kind
        print(f"{loc}/{site}: {kind} ({len(ov.get('questions', {}))} questions)")
coverage = {k: dict(sorted(v.items())) for k, v in sorted(coverage.items())}
with open(cov_path, "w") as f:
    json.dump(coverage, f, indent=1, sort_keys=True)
    f.write("\n")
