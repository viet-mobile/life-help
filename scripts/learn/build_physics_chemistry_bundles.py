def build_subject_bundle(site, data_list):
    skills = []
    courses = []
    questions = []

    for item in data_list:
        c_id = item["id"]
        c_grade = item["grade"]
        c_title = item["title"]
        c_world = item["world"]
        unit_spec = item["unit"]
        lesson_spec = item["lesson"]
        q_specs = item["questions"]

        l_id = lesson_spec["id"]
        l_title = lesson_spec["title"]
        l_concept = lesson_spec["concept"]
        l_example = lesson_spec["example"]
        sk_id = lesson_spec["skillId"]

        skills.append({"id": sk_id, "title": l_title})

        q_ids = []
        ch_id = None

        for q_idx, q_item in enumerate(q_specs):
            full_qid = f"{c_id}-{q_item['id_suffix']}"
            if q_item["role"] == "challenge":
                ch_id = full_qid
            else:
                q_ids.append(full_qid)

            options = []
            for i, opt_text in enumerate(q_item["opts"]):
                opt_id = chr(ord('a') + i)
                options.append({"id": opt_id, "text": opt_text})

            question_obj = {
                "id": full_qid,
                "site": site,
                "skillId": sk_id,
                "type": "multiple_choice",
                "difficulty": q_item["diff"],
                "prompt": q_item["prompt"],
                "options": options,
                "answer": {"kind": "choice", "id": q_item["ans"]},
                "hints": (q_item["hints"][:2] if len(q_item["hints"]) == 2 else ([q_item["hints"][0], " ".join(q_item["hints"][1:])] if len(q_item["hints"]) > 2 else q_item["hints"] + ["추가 힌트를 참고하세요."])),
                "explanation": q_item["expl"],
                "role": "core",
                "family": f"{c_id}-{q_item['role']}",
                "expectedSeconds": q_item["sec"],
                "status": "PUBLISHED"
            }
            questions.append(question_obj)

        unit_lessons = [{
            "id": l_id,
            "title": l_title,
            "concept": l_concept,
            "example": l_example,
            "skillIds": [sk_id],
            "questionIds": q_ids,
            "challengeId": ch_id
        }]

        course_units = [{
            "id": unit_spec["id"],
            "title": unit_spec["title"],
            "lessons": unit_lessons
        }]

        courses.append({
            "id": c_id,
            "title": c_title,
            "grade": c_grade,
            "world": c_world,
            "units": course_units
        })

    return {
        "catalog": {
            "site": site,
            "country": "kr",
            "curriculum": "kr-2022",
            "courses": courses,
            "skills": skills
        },
        "questions": questions
    }

def main():
    phy_bundle = build_subject_bundle("physics", PHYSICS_DATA)
    phy_path = PHYSICS_DIR / "physics.json"
    with open(phy_path, "w", encoding="utf-8") as f:
        json.dump(phy_bundle, f, ensure_ascii=False, indent=2)
    print(f"✅ Physics inquiry bundle created: {len(phy_bundle['catalog']['courses'])} courses, {len(phy_bundle['questions'])} questions in {phy_path}")

    chm_bundle = build_subject_bundle("chemistry", CHEMISTRY_DATA)
    chm_path = CHEMISTRY_DIR / "chemistry.json"
    with open(chm_path, "w", encoding="utf-8") as f:
        json.dump(chm_bundle, f, ensure_ascii=False, indent=2)
    print(f"✅ Chemistry inquiry bundle created: {len(chm_bundle['catalog']['courses'])} courses, {len(chm_bundle['questions'])} questions in {chm_path}")

if __name__ == "__main__":
    main()
