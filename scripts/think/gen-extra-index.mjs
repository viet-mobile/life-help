#!/usr/bin/env node
// Rewrites the generated indexes from lib/think/data/*.json + lib/think/data/extra/*.json + lib/think/i18n/<lang>/<key>.json:
//   lib/think/data/extra.ts   static imports of the extra batches (used by the self-contained review Worker bundle)
//   lib/think/data/files.ts   file metadata + lazy loaders for tasks and translations (used by the learning sites, code-split per file)
// Run after adding or removing a batch or a translation file.
import fs from "node:fs";
const dir = "lib/think/data/extra";
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort() : [];
const imp = files.map((f, i) => `import b${i} from "./extra/${f}";`).join("\n");
fs.writeFileSync("lib/think/data/extra.ts", `import type { ThinkTask } from "../types";\n${imp}\n\n// GENERATED by scripts/think/gen-extra-index.mjs from lib/think/data/extra/*.json - do not edit by hand.\nexport const extraFiles: ThinkTask[][] = [${files.map((_, i) => `b${i} as unknown as ThinkTask[]`).join(", ")}];\n`);

const LANGS = ["en", "zh-Hans", "zh-Hant", "ja", "vi", "ko"];
const entries = [
  ...["math", "english", "korean"].map((s) => ({ key: `pilot-${s}`, path: `./${s}.json`, tasks: JSON.parse(fs.readFileSync(`lib/think/data/${s}.json`, "utf8")) })),
  ...files.map((f) => ({ key: f.replace(/\.json$/, ""), path: `./extra/${f}`, tasks: JSON.parse(fs.readFileSync(`${dir}/${f}`, "utf8")) })),
];
const meta = entries.map((e) => ({ key: e.key, subject: e.tasks[0].subject, grades: [...new Set(e.tasks.map((t) => t.grade).filter(Boolean))].sort(), levels: [...new Set(e.tasks.map((t) => t.level))].sort(), count: e.tasks.length }));
const overlays = {};
for (const l of LANGS) { const d = `lib/think/i18n/${l}`; if (fs.existsSync(d)) overlays[l] = fs.readdirSync(d).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort(); }
const loaders = entries.map((e) => `  "${e.key}": () => import("${e.path}").then((m) => m.default as unknown as ThinkTask[]),`).join("\n");
const ovl = Object.entries(overlays).map(([l, keys]) => `  "${l}": {\n${keys.map((k) => `    "${k}": () => import("../i18n/${l}/${k}.json").then((m) => m.default as unknown as Overlay),`).join("\n")}\n  },`).join("\n");
fs.writeFileSync("lib/think/data/files.ts", `import type { ThinkTask } from "../types";

// GENERATED by scripts/think/gen-extra-index.mjs - do not edit by hand.
/** taskId -> (flat path -> translated string); see lib/think/flat.ts */
export type Overlay = Record<string, Record<string, string>>;
export interface FileMeta { key: string; subject: "math" | "english" | "korean"; grades: string[]; levels: number[]; count: number }
export const FILE_META: FileMeta[] = ${JSON.stringify(meta)};
export const TASK_LOADERS: Record<string, () => Promise<ThinkTask[]>> = {
${loaders}
};
export const OVERLAY_LOADERS: Record<string, Record<string, () => Promise<Overlay>>> = {
${ovl}
};
`);
console.log(`extra.ts: ${files.length} batch file(s); files.ts: ${meta.length} files, overlays: ${JSON.stringify(Object.fromEntries(Object.entries(overlays).map(([l, k]) => [l, k.length])))}`);
