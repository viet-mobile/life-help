#!/usr/bin/env node
// Rewrites lib/think/data/extra.ts from lib/think/data/extra/*.json (sorted). Run after adding or removing a batch file.
import fs from "node:fs";
const dir = "lib/think/data/extra";
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort() : [];
const imp = files.map((f, i) => `import b${i} from "./extra/${f}";`).join("\n");
const body = `import type { ThinkTask } from "../types";\n${imp}\n\n// GENERATED by scripts/think/gen-extra-index.mjs from lib/think/data/extra/*.json - do not edit by hand.\nexport const extraFiles: ThinkTask[][] = [${files.map((_, i) => `b${i} as unknown as ThinkTask[]`).join(", ")}];\n`;
fs.writeFileSync("lib/think/data/extra.ts", body);
console.log(`extra.ts: ${files.length} batch file(s)`);
