locales.forEach(loc => {
  const filePath = path.join(__dirname, '..', 'messages', `${loc}.json`);
  if (!fs.existsSync(filePath)) return;
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  if (!data.chat) data.chat = {};

  const specific = workstationTranslations[loc] || {};
  const enDefault = workstationTranslations['en'];

  for (const [k, v] of Object.entries(enDefault)) {
    data.chat[k] = specific[k] || data.chat[k] || v;
  }

  // If specific translations exist for workstation keys, merge them
  if (specific) {
    for (const [k, v] of Object.entries(specific)) {
      data.chat[k] = v;
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
});

