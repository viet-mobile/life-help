/**
 * Where curriculum content comes from. The default source is the bundled demo
 * curriculum (data files, never inline in components). A Supabase-backed source
 * implements the same interface (see supabaseContent.ts).
 */
export interface ContentRepository {
  getBundle(site: Site): Promise<ContentBundle>;
}

/**
 * Elementary (E1..E6) courses first, then the existing M1 demo course, then the grade-specific secondary courses (M2..H3).
 * Courses, skills and questions are disjoint by id.
 */
function mergeBundles(elementary: ContentBundle, demo: ContentBundle, secondary: ContentBundle): ContentBundle {
  return {
    catalog: {
      ...demo.catalog, // country / curriculum identifiers stay those of the existing curriculum (one curriculum row per subject in the database too)
      skills: [...elementary.catalog.skills, ...demo.catalog.skills, ...secondary.catalog.skills],
      courses: [...elementary.catalog.courses, ...demo.catalog.courses, ...secondary.catalog.courses],
    },
    questions: [...elementary.questions, ...demo.questions, ...secondary.questions],
  };
}
const demoBundles: Record<Site, ContentBundle> = {
  math: publishedOnly(mergeBundles(mathElementary as unknown as ContentBundle, mathDemo as unknown as ContentBundle, mathSecondary as unknown as ContentBundle)),
  english: publishedOnly(mergeBundles(englishElementary as unknown as ContentBundle, englishDemo as unknown as ContentBundle, englishSecondary as unknown as ContentBundle)),
  korean: publishedOnly(korean as unknown as ContentBundle), // generated by scripts/learn/korean/build-korean-content.mjs
};

export const demoContentRepository: ContentRepository = {
  async getBundle(site) {
    return demoBundles[site]; // the same object every call, so localised copies can be memoised
  },
};

let activeRepository: ContentRepository = demoContentRepository;
export function setContentRepository(repo: ContentRepository) {
  activeRepository = repo;
}
export function getContentRepository(): ContentRepository {
  return activeRepository;
}

/**
 * Curriculum for one request. `grade` scopes the learning path, the placement pool, the skills and the questions to that student's
 * grade (see scopeToGrade); `locale` swaps the learner-facing strings for that locale's overlay. Neither changes ids, question types
 * or answer keys.
 */
export async function loadIndex(site: Site, opts: { grade?: Grade; locale?: LearnLocale; bank?: boolean; bankQuestionId?: string } = {}): Promise<{ bundle: ContentBundle; index: ContentIndex }> {
  // study.korean is code-reviewed bundled content only (the database content source holds math / english): never a DB round trip.
  let bundle = await (site === "korean" ? demoContentRepository : getContentRepository()).getBundle(site);
  if (opts.locale) bundle = await localizedBundle(bundle, opts.locale);
  // The parametric practice bank (bank.ts) joins the server-side bundle only: pages and the browser's metadata ask with bank:false.
  if (opts.bank !== false && hasBank(site)) {
    const locale = opts.locale ?? siteConfig(site).presentationLocale;
    const ov = locale === siteConfig(site).presentationLocale ? null : await overlayFor(locale, site);
    const skills = new Set(bundle.catalog.skills.map((s) => s.id));
    let extra = bankQuestions(site, locale, ov?.bank, skills, `${skills.size}`);
    if (site === "english") {
      // English practice bank: server-only assets, read for the skills this request can reach (one question's skill, the learner's grade scope, or all)
      let wanted: ReadonlySet<string> = skills;
      if (opts.bankQuestionId) {
        const sk = (await loadEnglishBankIndex()).get(opts.bankQuestionId);
        wanted = new Set(sk && skills.has(sk) ? [sk] : []);
      } else if (opts.grade) wanted = new Set(scopeToGrade(bundle, opts.grade).catalog.skills.map((s) => s.id));
      const raw = await loadEnglishBank(wanted);
      extra = locale === siteConfig("english").presentationLocale ? raw : localizeEnglishBank(raw, ov?.bank, locale);
    }
    if (extra.length) bundle = { ...bundle, questions: [...bundle.questions, ...extra] };
  }
  if (site === "english") bundle = { ...bundle, questions: gateAll(bundle.questions, !!opts.locale && opts.locale !== siteConfig("english").presentationLocale) }; // hint 2 fail-closed (lib/learn/hintGate.ts)
  if (opts.grade) bundle = scopeToGrade(bundle, opts.grade);
  return { bundle, index: indexContent(bundle) };
}

/** Strip server-only fields (answer key, hints, explanation) for the browser. */
export function toPublicQuestion(q: Question): PublicQuestion {
  return {
    id: q.id,
    site: q.site,
    skillId: q.skillId,
    type: q.type,
    difficulty: q.difficulty,
    prompt: q.prompt,
    latex: q.latex,
    figure: q.figure,
    options: q.options,
    audioText: q.audioText,
    target: q.target,
    hintCount: q.hints.length,
  };
}

/** Id + skill (+ role) of every English-bank question, for the access plan: no answers, hints or explanations. */
export async function bankIndexEntries(site: Site): Promise<Array<{ id: string; skillId: string; role: "variant" }>> {
  if (site !== "english") return [];
  return [...(await loadEnglishBankIndex())].map(([id, skillId]) => ({ id, skillId, role: "variant" as const }));
}
